/**
 * Configuration options for `@fastify-utils/error`.
 *
 * @example
 * ```typescript
 * configure({
 *     baseUrl: "https://api.example.com/errors"
 * })
 * ```
 */
export interface ErrorConfig {
    /**
     * Base URL prefix for generating RFC 9457 `type` URI references.
     * Defaults to `"about:blank"` (or the value of the `RFC9457_BASE_URL` environment variable).
     *
     * - When `"about:blank"`: types are generated as `"about:blank#<error-name>"`
     * - When a custom URI is provided: types are generated as `"<baseUrl>/<error-name>"`
     */
    baseUrl?: string
}

/**
 * Parameters used to construct an {@link HttpError} instance.
 *
 * @example
 * ```typescript
 * const params: HttpErrorParams = {
 *     type: "about:blank#not-found",
 *     title: "Not Found",
 *     status: 404,
 *     detail: "User 123 not found",
 *     instance: "/users/123"
 * }
 * ```
 */
export interface HttpErrorParams {
    /**
     * A URI reference that identifies the problem type (RFC 9457 Section 3.1.1).
     */
    type: string
    /**
     * A short, human-readable summary of the problem type (RFC 9457 Section 3.1.2).
     */
    title: string
    /**
     * The HTTP status code generated by the origin server for this occurrence of the problem (RFC 9457 Section 3.1.3).
     */
    status: number
    /**
     * A human-readable explanation specific to this occurrence of the problem (RFC 9457 Section 3.1.4).
     */
    detail: string
    /**
     * An optional URI reference that identifies the specific occurrence of the problem (RFC 9457 Section 3.1.5).
     */
    instance?: string
    /**
     * An optional underlying `Error` that caused this error, preserved for debugging and stack inspection.
     */
    cause?: Error
}

/**
 * Map of field names to arrays of error messages representing validation failures.
 *
 * @example
 * ```typescript
 * const validationErrors: ValidationErrors = {
 *     email: ["Invalid email format", "Email must be unique"],
 *     password: ["Must be at least 8 characters"]
 * }
 * ```
 */
export interface ValidationErrors {
    [field: string]: string[]
}
